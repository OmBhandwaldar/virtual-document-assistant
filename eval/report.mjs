// eval/report.mjs
// Generates the numbers block of the README "Retrieval Quality" section from the result
// files in eval/results/, so every number in the README comes from a committed file.
// Only the current pipeline is reported (after.json + the chunk-size sweep).
//
//   node eval/report.mjs          # rewrite the block between the markers in README.md
//   node eval/report.mjs --check  # exit 1 if README.md is out of date
import fs from "node:fs";

const START = "<!-- eval-report:start (generated by `node eval/report.mjs`; do not edit by hand) -->";
const END = "<!-- eval-report:end -->";
const load = (name) => ({ name, ...JSON.parse(fs.readFileSync(`eval/results/${name}.json`, "utf8")) });

const after = load("after");
const sweep = ["sweep-200w", "sweep-350w", "sweep-500w"].map(load);

const f3 = (x) => (x === null || x === undefined ? "n/a" : x.toFixed(3));
const sum = (r, k) => Object.values(r.corpus).reduce((s, c) => s + c[k], 0);
const o = (r) => r.metrics.overall;
const cfg = (r) => `${r.pipeline.chunking.targetWords} words, ${r.pipeline.chunking.overlapWords} overlap`;
const fileLink = (r) => `[\`${r.name}.json\`](eval/results/${r.name}.json)`;

const best = [...sweep].sort((a, b) => o(b).mrrAt5 - o(a).mrrAt5)[0];
const pdfs = Object.keys(after.metrics.byPdf);
const pages = Object.values(after.corpus).reduce((s, c) => s + c.pages, 0);

const repeatSource = sweep.find(
  (r) =>
    r.pipeline.chunking.targetWords === after.pipeline.chunking.targetWords &&
    r.pipeline.chunking.overlapWords === after.pipeline.chunking.overlapWords
);
const repeatDiffs = repeatSource
  ? after.perQuestion.filter((q) => q.firstHitRankStored !== repeatSource.perQuestion.find((p) => p.id === q.id)?.firstHitRankStored).length
  : null;

const m = o(after);
const block = `${START}
**Results** (${fileLink(after)}: ${m.questions} questions over ${pdfs.length} PDFs / ${pages} pages, top-${after.retrieval.topK}, ${cfg(after)}):

| Metric | Value |
|---|---|
| **Citation accuracy** | **${f3(m.citationAccuracy)}** (${m.citationsLocated} citations checked) |
| **Recall@1** (cited page) | **${f3(m.recallAt1)}** |
| **Recall@5** (cited page) | **${f3(m.recallAt5)}** |
| **MRR@5** (cited page) | **${f3(m.mrrAt5)}** |
| Recall@5 (true page) | ${f3(m.recallAt5_truePage)} |

| Document | Recall@1 | Recall@5 | MRR@5 |
|---|---|---|---|
${pdfs.map((p) => `| \`${p}\` | ${f3(after.metrics.byPdf[p].recallAt1)} | ${f3(after.metrics.byPdf[p].recallAt5)} | ${f3(after.metrics.byPdf[p].mrrAt5)} |`).join("\n")}

**Chunk-size sweep** (default chosen by MRR@5: **${best.pipeline.chunking.targetWords} words**):

| Run | Chunk size | Chunks | Citation accuracy | Recall@1 | Recall@5 | MRR@5 |
|---|---|---|---|---|---|---|
${sweep.map((r) => `| ${fileLink(r)} | ${cfg(r)} | ${sum(r, "chunks")} | ${f3(o(r).citationAccuracy)} | ${f3(o(r).recallAt1)} | ${f3(o(r).recallAt5)} | ${f3(o(r).mrrAt5)} |`).join("\n")}

MRR@5 per document, showing how chunk size trades off between document types:

| Run | ${pdfs.map((p) => `\`${p}\``).join(" | ")} |
|---|${pdfs.map(() => "---").join("|")}|
${sweep.map((r) => `| ${r.name} | ${pdfs.map((p) => f3(r.metrics.byPdf[p]?.mrrAt5)).join(" | ")} |`).join("\n")}

${repeatSource ? `Repeatability: \`after\` and \`${repeatSource.name}\` are two independent ingestions with the same config; ${repeatDiffs} of ${after.perQuestion.length} questions changed rank between them.` : ""}
Every embedding is linked to its chunk (${sum(after, "embeddingsLinkedToChunk")} of ${sum(after, "embeddings")}); model \`${after.pipeline.embedding.model}\`, ${after.pipeline.embedding.dimensionObservedInDb} dimensions, task types \`${after.pipeline.embedding.documentTaskType}\` / \`${after.pipeline.embedding.queryTaskType}\`.
${END}`;

const readme = fs.readFileSync("README.md", "utf8");
const re = new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`);
if (!re.test(readme)) throw new Error("README.md has no eval-report markers");
const next = readme.replace(re, block);

if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md eval report is out of date; run `node eval/report.mjs`");
    process.exit(1);
  }
  console.log("README.md eval report is up to date");
} else {
  fs.writeFileSync("README.md", next);
  console.log("README.md eval report updated");
}

function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
