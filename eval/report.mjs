// eval/report.mjs
// Generates the numbers block of the README "Retrieval Quality" section from the result
// files in eval/results/, so every number in the README comes from a committed file.
//
//   node eval/report.mjs          # rewrite the block between the markers in README.md
//   node eval/report.mjs --check  # exit 1 if README.md is out of date
import fs from "node:fs";

const START = "<!-- eval-report:start (generated by `node eval/report.mjs`; do not edit by hand) -->";
const END = "<!-- eval-report:end -->";
const load = (name) => ({ name, ...JSON.parse(fs.readFileSync(`eval/results/${name}.json`, "utf8")) });

const baseline = load("baseline");
const after = load("after");
const freeTier = load("baseline-freetier-asis");
const sweep = ["sweep-200w", "sweep-350w", "sweep-500w"].map(load);

const f3 = (x) => (x === null || x === undefined ? "n/a" : x.toFixed(3));
const sum = (r, k) => Object.values(r.corpus).reduce((s, c) => s + c[k], 0);
const o = (r) => r.metrics.overall;
const chunkCfg = (r) =>
  r.pipeline.chunking.unit === "words"
    ? `${r.pipeline.chunking.targetWords} words, ${r.pipeline.chunking.overlapWords} overlap`
    : `${r.pipeline.chunking.size} chars, ${r.pipeline.chunking.overlap} overlap`;
const row = (label, r) =>
  `| ${label} | ${f3(o(r).citationAccuracy)} | ${f3(o(r).recallAt1)} | ${f3(o(r).recallAt5)} | ${f3(o(r).mrrAt5)} | ${f3(o(r).recallAt5_truePage)} | ${f3(o(r).mrrAt5_truePage)} | ${sum(r, "chunks")} |`;
const HEADER = `| Run | Citation accuracy | Recall@1 | Recall@5 | MRR@5 | Recall@5 (true page) | MRR@5 (true page) | Chunks |
|---|---|---|---|---|---|---|---|`;

const best = [...sweep].sort((a, b) => o(b).mrrAt5 - o(a).mrrAt5)[0];

// paired per-question comparison of where the first relevant chunk is ranked (true page; 6 = not in top 5)
const rankOf = (r, id) => r.perQuestion.find((q) => q.id === id)?.firstHitRankTrue ?? 6;
const paired = (a, b) => {
  let better = 0, worse = 0, same = 0;
  for (const q of a.perQuestion) {
    const x = rankOf(a, q.id), y = rankOf(b, q.id);
    if (y < x) better++;
    else if (y > x) worse++;
    else same++;
  }
  return { better, worse, same };
};
const pr = paired(baseline, after);
const repeatSource = sweep.find(
  (r) => r.pipeline.chunking.targetWords === after.pipeline.chunking.targetWords && r.pipeline.chunking.overlapWords === after.pipeline.chunking.overlapWords
);
const repeatDiffs = repeatSource
  ? after.perQuestion.filter((q) => q.firstHitRankStored !== repeatSource.perQuestion.find((p) => p.id === q.id)?.firstHitRankStored).length
  : null;
const pdfs = Object.keys(after.metrics.byPdf);
const perPdfTable = `| Run | ${pdfs.map((p) => `MRR@5 ${p}`).join(" | ")} |
|---|${pdfs.map(() => "---").join("|")}|
${[baseline, ...sweep]
  .map((r) => `| ${r.name} | ${pdfs.map((p) => f3(r.metrics.byPdf[p]?.mrrAt5_truePage)).join(" | ")} |`)
  .join("\n")}`;
const fileLink = (r) => `[\`${r.name}.json\`](eval/results/${r.name}.json)`;

const block = `${START}
**Before / after** (50 questions, top-5, same frozen labels):

${HEADER}
${row(`Before: ${fileLink(baseline)} (${chunkCfg(baseline)})`, baseline)}
${row(`After: ${fileLink(after)} (${chunkCfg(after)})`, after)}

**Chunk-size sweep** (new pipeline, chosen default by MRR@5 = **${best.pipeline.chunking.targetWords} words**):

${HEADER}
${sweep.map((r) => row(`${fileLink(r)} (${chunkCfg(r)})`, r)).join("\n")}

Per-PDF MRR@5 (true page), showing the size trade-off between documents:

${perPdfTable}

Question by question (rank of the first relevant chunk, true page), after vs before:
${pr.better} better, ${pr.worse} worse, ${pr.same} unchanged.
${repeatSource ? `Repeatability: \`after\` and \`${repeatSource.name}\` are two independent ingestions with the same config; ${repeatDiffs} of ${after.perQuestion.length} questions changed rank between them.` : ""}

**Free-tier embedding loss (old pipeline):** with a free-tier Gemini key, the old upload route embedded
**${sum(freeTier, "embeddings")} of ${sum(freeTier, "chunks")} chunks**
(${((1 - sum(freeTier, "embeddings") / sum(freeTier, "chunks")) * 100).toFixed(0)}% lost): its batches of 100
hit the 100 requests/min limit and failed batches were skipped without an error, leaving two of three PDFs
with no embeddings at all (${fileLink(freeTier)}). The new pipeline retries with backoff and fails loudly
instead; a test covers this (\`npm test\`).

Embeddings linked to their chunk: before ${sum(baseline, "embeddingsLinkedToChunk")} of ${sum(baseline, "embeddings")},
after ${sum(after, "embeddingsLinkedToChunk")} of ${sum(after, "embeddings")}.
Model \`${after.pipeline.embedding.model}\`, ${after.pipeline.embedding.dimensionObservedInDb} dimensions
(task types before: none; after: \`${after.pipeline.embedding.documentTaskType}\` / \`${after.pipeline.embedding.queryTaskType}\`).
${END}`;

const readme = fs.readFileSync("README.md", "utf8");
const re = new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`);
if (!re.test(readme)) throw new Error("README.md has no eval-report markers");
const next = readme.replace(re, block);

if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md eval report is out of date; run `node eval/report.mjs`");
    process.exit(1);
  }
  console.log("README.md eval report is up to date");
} else {
  fs.writeFileSync("README.md", next);
  console.log("README.md eval report updated");
}

function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
